"""Environment-event sync stubs, live (test before the built-in version):
python diag/twin/env_live.py install AB     cave stubs + 3 hooks (JIT-safe)
python diag/twin/env_live.py box A          print the env box (id, armed, mode, drawn, count)
python diag/twin/env_live.py mode B 1       set B's mode (1 = wait for the host's id)
python diag/twin/env_live.py give B ID      arm B's box with ID"""
import struct
import sys

sys.path.insert(0, 'diag/twin')
from mem import Mem

EB, CA = 0x492AFC0, 0x492AE80  # box print shows +0..+0x10
CAVE = bytes([0x09, 0x0A, 0x00, 0x10, 0x29, 0x09, 0x40, 0xB9, 0x49, 0x00, 0x00, 0x34, 0xDF, 0x49, 0x17, 0x17, 0xF5, 0x49, 0x17, 0x17, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x09, 0x09, 0x00, 0x10, 0x2A, 0x05, 0x40, 0xB9, 0xCA, 0x00, 0x00, 0x34, 0x2B, 0x01, 0x40, 0xB9, 0x4B, 0x00, 0x00, 0xB9, 0x3F, 0x05, 0x00, 0xB9, 0x80, 0x00, 0x80, 0x52, 0xC0, 0x03, 0x5F, 0xD6, 0x00, 0x00, 0x80, 0x52, 0xC0, 0x03, 0x5F, 0xD6, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x89, 0x07, 0x00, 0x10, 0x20, 0x0D, 0x00, 0xB9, 0x2A, 0x11, 0x40, 0xB9, 0x4A, 0x05, 0x00, 0x11, 0x2A, 0x11, 0x00, 0xB9, 0xB8, 0x4B, 0x17, 0x17])
HOOKS = [(0xEFD604, 0x14E8B61F, (0x5400030B, 0x14000018)), (0xEFD63C, 0x94E8B619, (0xD63F0100,)),
         (0xEFDD4C, 0x94E8B461, (0x9400001E,))]

op, games = sys.argv[1], sys.argv[2]
for w in games:
    m = Mem(w)
    if op == 'install':
        m.write(m.base + EB, bytes(20))
        m.write(m.base + CA, CAVE, code=True)
        for off, new, olds in HOOKS:
            have = m.u32(m.base + off)
            if have in olds:
                m.write(m.base + off, struct.pack('<I', new), code=True)
                print(w, hex(off), '%08x -> %08x' % (have, new))
            else:
                print(w, hex(off), 'is %08x, not patched' % have)
    elif op == 'box':
        print(w, 'id %d armed %d mode %d drawn %d count %d' % struct.unpack('<iIIiI', m.read(m.base + EB, 20)))
    elif op == 'mode':
        m.write(m.base + EB + 8, struct.pack('<I', int(sys.argv[3])))
    elif op == 'give':
        m.write(m.base + EB, struct.pack('<iI', int(sys.argv[3]), 1))
