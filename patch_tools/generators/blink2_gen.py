"""blink2_gen (alpha 17): BLINK_SHARE also sends the six-digit skill family 140000..149999 (Vanish Dash: 140070,
140171, 140072, 142643, measured live 2026-11-21) next to 1400000..1449999. The hook 0x194B8A8 and its trampoline
0x18CB9C4..0x18CB9D0 are already built in (blink_gen.py, which cannot re-run on a shipped site), so this only
  - claims a NEW far cave BLINK2 (the old BLINK cave 0xC501870..0xC5018A0 stays, unused), and
  - re-points the three trampoline words at it.
    python blink2_gen.py [--claim]     (from diag/net; writes blink2_live.py)
Bake: python tools/add_dusk_records.py diag/net/blink2_live.py BLINK2_CAVE, then
      python tools/update_dusk_records.py diag/net/blink2_live.py BLINK2_TRAMP (three UPDATEs)."""
import sys

import cave_lib as C

CLAIM = '--claim' in sys.argv
OUT = 'blink2_live.py'
SITE, BACK, PAD = 0x194B8A8, 0x194B8AC, 0x18CB9C4
LO_ID, SPAN = 1400000, 50000
LO_ID2, SPAN2 = 140000, 10000


def cset_hs(rd):                        # cset wd, hs = csinc wd, wzr, wzr, lo
    return 0x1A9F37E0 | C.R(rd)


def sub_wr(rd, rn, rm):
    return 0x4B000000 | (C.R(rm) << 16) | (C.R(rn) << 5) | C.R(rd)


def ccmp_w_hs(rn, rm):                  # ccmp wn, wm, #0, hs: flags = cmp(wn, wm) if hs, else nzcv = 0 (lo)
    return 0x7A400000 | (C.R(rm) << 16) | (0b0010 << 12) | (C.R(rn) << 5)


def asm(start):
    a = C.Asm(start)
    a(C.ldur_w(16, 29, -8))                                  # the SpEffect id (x1 = x29 - 8)
    a(C.movz_w(17, LO_ID & 0xFFFF))
    a(C.movk_w(17, LO_ID >> 16, 1))
    a(sub_wr(17, 16, 17))
    a(C.movz_w(5, SPAN))                                     # w5 is free here: the hooked word sets it
    a(C.cmp_wr(17, 5))                                       # lo = in 1400000..1449999
    a(C.movz_w(17, LO_ID2 & 0xFFFF))
    a(C.movk_w(17, LO_ID2 >> 16, 1))
    a(sub_wr(17, 16, 17))
    a(C.movz_w(5, SPAN2))
    a(ccmp_w_hs(17, 5))                                      # not in the first range: lo = in 140000..149999
    a(cset_hs(5))                                            # w5 = 0 (send) for either range, else 1
    a.many(lambda pc, L: C.far_return(pc, BACK, 'x16'))
    return a


# the built-in hook and trampoline this relies on
assert C.SHIPPED.get(SITE) is not None or SITE in C.SHIPPED, 'hook 0x194B8A8 is not built in'
g = C.Gen('blink2_gen', out=OUT, dry=not CLAIM)
n = len(asm(0xC500000).words())
start = g.alloc('BLINK2', 'FAR_CODE', (n * 4 + 15) // 16 * 16, 'BLINK_SHARE (alpha 17): TAE skill SpEffects '
                '1400000..1449999 and 140000..149999 sent to the copies (w5 = 0) at 0x194B8A8; trampoline '
                '0x18CB9C4 re-pointed here; the old BLINK cave is unused')
cave = g.cave('BLINK2', start, asm(start))
assert C.dis1(start + 44, cset_hs(5)) == 'cset w5, hs', C.dis1(start + 44, cset_hs(5))
assert C.dis1(start + 40, ccmp_w_hs(17, 5)) == 'ccmp w17, w5, #0, hs', C.dis1(start + 40, ccmp_w_hs(17, 5))
tramp = [(PAD + 4 * k, '00000000', '%08X' % int.from_bytes(w.to_bytes(4, 'little'), 'big'), True)
         for k, w in enumerate(C.far_jump(PAD, start))]
groups = {'BLINK2_CAVE': cave, 'BLINK2_TRAMP': tramp}
ORDER = ['BLINK2_CAVE', 'BLINK2_TRAMP']
print('\n'.join(g.listing))
for i, w in enumerate(asm(start).words()):
    print('  %X  %s' % (start + 4 * i, C.dis1(start + 4 * i, w)))
C.write_live(OUT, groups, ORDER, """
BLINK_SHARE, alpha 17 (generated by blink2_gen.py): the TAE SpEffect apply at 0x194B8A8 sends the skill families
1400000..1449999 and 140000..149999 to the other games' copies. New far cave BLINK2; the built-in trampoline
0x18CB9C4..0x18CB9D0 is re-pointed at it (UPDATE of three existing records). The hook word itself is unchanged.""")
print('cave at 0x%X, %d words; %s' % (start, n, 'CLAIMED' if CLAIM else 'DRY'))
