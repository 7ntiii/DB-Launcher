"""Generator + checker for the bell reward group in bell_live.py. Static only (reads nso/*.bin and
src/lichii/src/core/file_sys/patch_manager.cpp, writes bell_live.py, prints capstone listings).
python bell_gen.py

Group (design and [V]/[I] marks: bell_notes.md):
  BELL_REWARD  Dusk's Toll (env event 1300, type 0x26) reward grant runs in LAN. Two in-place nops, no cave:
    0xD6A48C  cbz w8 (+0xBDA)   in the condition's grant step 0xD6A464 (vt+0x18 of vtable main+0x56D84D8)
    0xF0EAAC  b.eq (mode == 6)  in the support object's grant 0xF0EA78 (par+0x2C0, only caller 0xD6A5DC)
  Online both skip: the server granted the bell reward. With them every game that runs the bell sequence grants the
  holder's Virtue (wp counter 120000 via 0xF0EBC0) on its own copy of the holder; copies' counters do not count
  (dusk_lan.cpp VIRTUE_COPY_COUNTERS_OFF = true), so only the ringer's own game adds to the shared total."""
import os
import re
import struct

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
N = os.path.join(HERE, 'nso')
TXT = open(os.path.join(N, 'main_text.bin'), 'rb').read()
PM = os.path.join(HERE, '..', '..', 'src', 'lichii', 'src', 'core', 'file_sys', 'patch_manager.cpp')
md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)

# ---------------------------------------------------------------- shipped records (patch_manager.cpp)
src = open(PM, encoding='utf-8', errors='ignore').read()
arrays = {}
for m in re.finditer(r'constexpr\s+std::array<u8,\s*(\d+)>\s+(\w+)\s*\{([^}]*)\}', src):
    n, name, body = int(m.group(1)), m.group(2), m.group(3)
    vals = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{1,2})\b', body)]
    arrays[name] = bytes(vals) + b'\0' * (n - len(vals))
shipped = {}
for m in re.finditer(r'BuiltinPatchRecord\{\s*0x([0-9A-Fa-f]+),\s*(\w+)', src):
    a, name = int(m.group(1), 16), m.group(2)
    if name not in arrays:
        continue
    for i, bt in enumerate(arrays[name]):
        shipped[a + i] = bt
print('shipped bytes parsed: %d' % len(shipped))


def word(off):
    return struct.unpack_from('<I', TXT, off)[0]


def hexw(w):
    return struct.pack('<I', w).hex().upper()


def dis1(addr, w):
    ins = list(md.disasm(struct.pack('<I', w), addr))
    assert len(ins) == 1, 'undecodable %08x at %x' % (w, addr)
    return ins[0].mnemonic + (' ' + ins[0].op_str if ins[0].op_str else '')


NOP = 0xD503201F
listing = []
groups = {}


def text_patch(addr, expect, new, note):
    old = word(addr)
    got = dis1(addr, old)
    assert got == expect, 'at %x: %s, expected %s' % (addr, got, expect)
    assert not any(addr + i in shipped for i in range(4)), 'collides with a shipped record at %x' % addr
    listing.append('  0x%x  %s  ->  %s   (%s)' % (addr, got, dis1(addr, new), note))
    return (addr, hexw(old), hexw(new), True)


def ctx(addr, expect):
    got = dis1(addr, word(addr))
    assert got == expect, 'context %x: %s, expected %s' % (addr, got, expect)
    listing.append('  context 0x%x: %s' % (addr, got))


# ================================================================ BELL_REWARD
listing.append('=== BELL_REWARD')
# condition vt+0x18 = 0xD6A450: cond+8 (pending user) != -1 -> 0xD6A464
ctx(0xD6A450, 'ldr w8, [x0, #8]')
ctx(0xD6A45C, 'b #0xd6a464')
ctx(0xD6A484, 'ldr x8, [x8, #0xc20]')
ctx(0xD6A488, 'ldrb w8, [x8, #0xbda]')
ctx(0xD6A5DC, 'bl #0xf0ea78')
ctx(0xD6A5E0, 'mov w8, #-1')            # cond+8 = -1 afterwards (one grant per queued user)
ctx(0xF0EAA4, 'ldr w8, [x8, #0x1268]')
ctx(0xF0EAA8, 'cmp w8, #6')
ctx(0xF0EB70, 'bl #0xf0ebc0')
ctx(0xF0EC7C, 'ldrb w9, [x19, #8]')
ctx(0xF0EC80, 'cmp w9, #0x26')          # bell env type -> Virtue counter 120000
ctx(0xF0EC90, 'mov w1, #0xd4c0')
groups['BELL_REWARD'] = [
    text_patch(0xD6A48C, 'cbz w8, #0xd6a5e0', NOP, 'condition grant step runs online (was offline only)'),
    text_patch(0xF0EAAC, 'b.eq #0xf0eb74', NOP, 'support-object grant runs in session mode 6'),
]

# 0xF0EA78 has a single caller (0xD6A5DC); 0xF0EBC0 is also reached from the server functor 0xF13964 (untouched)
callers = []
for o in range(0, len(TXT) - 3, 4):
    w = struct.unpack_from('<I', TXT, o)[0]
    if (w & 0x7C000000) == 0x14000000:
        imm = w & 0x3FFFFFF
        if imm & 0x2000000:
            imm -= 0x4000000
        if o + imm * 4 == 0xF0EA78:
            callers.append(o)
assert callers == [0xD6A5DC], 'callers of 0xF0EA78: %s' % [hex(c) for c in callers]
listing.append('  0xF0EA78 callers: %s (only the bell condition)' % [hex(c) for c in callers])

print('\n'.join(listing))
out = ['"""Bell reward patch group: (offset_from_main, orig_hex, new_hex, is_code). Bytes little-endian as in memory.',
       'Generated by bell_gen.py (original-word checks, capstone listing, collision check against patch_manager.cpp).',
       'Not live-tested. No cave. Apply on EVERY game. Notes: bell_notes.md."""', '',
       'BELL_REWARD = [  # Dusk\'s Toll reward (Virtue counter 120000) granted in LAN by the games that run the bell sequence']
for a, o, n, c in groups['BELL_REWARD']:
    out.append('    (0x%X, "%s", "%s", %s),' % (a, o, n, c))
out += [']', '', 'ORDER = [BELL_REWARD]']
open(os.path.join(HERE, 'bell_live.py'), 'w').write('\n'.join(out) + '\n')
print('bell_live.py written')
