"""breakshare_gen: BREAK_SHARE - breakables (delayed geom model creation, message 0x71) reach every game
(deep_audit_F F10, deep_audit_F_fixes.md). Static only: reads nso/*.bin, patch_manager.cpp and every *_live.py;
writes breakshare_live.py; prints a capstone listing.     python breakshare_gen.py   (from diag/net)

Code [V]:
  - request 0xFB0680 (callers 0xE30994, 0x18C76F4): finds the object, builds a 0xA0-byte record and sends it with
    transport vt+0x48 (to the server member; in LAN that is the game's own self link) at 0xFB0780;
  - broadcast 0xFB0120 (the server's answer path): returns at once when the session has members (0xFB0168), so
    in LAN it never sends;
  - reader 0xFAF120 reads 0x71 only from the server member (vt+0x60 at 0xFAF314), i.e. only its own request.
  So today each game shows only its own breaks.
BREAK_SHARE (2 words, every game):
  0xFB0780 ldr x8, [x8, #0x48] -> #0x40   the request is broadcast (every member and the self link, attribute
                                          0x00 of type 0x71 = all; the same change as the lever relay A1)
  0xFAF314 ldr x8, [x8, #0x60] -> #0x50   read 0x71 from anyone (same as the lever relay A2; x4 = xzr kept)
Each game then gets every request once (its own over the self link, the others' over their links) and applies it
with the same reader code it uses for its own today. No double apply: the broadcast path 0xFB0120 stays silent
with members, and the request no longer goes to the server member separately.
"""
import sys

import cave_lib as C

for a, t in [(0xFB0770, 'ldr x8, [x0, #0x10]!'), (0xFB0778, 'mov w1, #0x71'), (0xFB077C, 'mov w3, #0xa0'),
             (0xFB0784, 'blr x8'),
             (0xFB0164, 'cmp w8, #0'), (0xFB0168, 'b.le #0xfb0188'), (0xFB02A8, 'ldr x8, [x8, #0x40]'),
             (0xFAF30C, 'mov w1, #0x71'), (0xFAF310, 'mov w3, #0xa0'), (0xFAF318, 'mov x4, xzr'),
             (0xFAF31C, 'blr x8')]:
    got = C.dis1(a, C.text_word(a))
    assert got == t, 'context %x: %s, expected %s' % (a, got, t)
# the lever relay uses the same two vtable slots (built in): send vt+0x40, read-from-anyone vt+0x50
assert C.dis1(0xD68FC0, C.shipped_word(0xD68FC0)) == 'ldr x8, [x8, #0x40]', 'lever relay A1 not built in'
assert C.dis1(0xD68658, C.shipped_word(0xD68658)) == 'ldr x8, [x8, #0x50]', 'lever relay A2 not built in'

g = C.Gen('breakshare_gen', 'breakshare_live.py')
groups = {'BREAK_SHARE': [
    g.text_patch(0xFB0780, 'ldr x8, [x8, #0x48]', C.ldr_x(8, 8, 0x40), '0x71 request broadcast to every member'),
    g.text_patch(0xFAF314, 'ldr x8, [x8, #0x60]', C.ldr_x(8, 8, 0x50), '0x71 read from anyone')]}
print('\n'.join(g.listing))
C.write_live('breakshare_live.py', groups, ['BREAK_SHARE'], """
BREAK_SHARE (generated by breakshare_gen.py; deep_audit_F F10, deep_audit_F_fixes.md): breakables / delayed geom
pieces (message 0x71) are sent to every game and read from anyone. Apply on EVERY game. Not live-tested.""")
d, r = C.cpp_rows('BREAK_SHARE', groups['BREAK_SHARE'])
print(d + '\n' + r)
