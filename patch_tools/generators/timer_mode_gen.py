"""timer_mode_gen: TIMER_MODE - the host's phase countdown is missing in the final (timer4_notes.md, match 3 probe4).
Static only: reads nso/*.bin, patch_manager.cpp and every *_live.py; writes timer_mode_live.py; prints a listing.
    python timer_mode_gen.py        (from diag/net)
Then: python tools/bake_check.py timer_mode_live.py TIMER_MODE

Code [V]:
  - 0x12C9160 (the phase clock's only data source; single caller 0x13A1B40 in the phase clock update 0x13A1AE0)
    returns in the low byte of x0 `par+0x3388 != 0` (0x12C9194 ldr, 0x12C91A4 cmp, 0x12C91A8 cset, stored at sp+0x14,
    returned at 0x12C93E8 / 0x12C93F0 -> 0x12C9408). par+0x3388 is the point-select coordinator.
  - 0x13A1AE0 stores that byte at obj+0xA and, when it is non-zero, takes the coordinator display (0x13A1B94..:
    0x155E280, sh +0x280) instead of the phase countdown (0x13A1BE8). Probe4 (match 3 final): A (host) obj+0xA = 1,
    segments 0, +0x14/+0x18 = -1 (no countdown drawn); B (guest, no coordinator) obj+0xA = 0, 6 segments, countdown.
  - In LAN only the host keeps a coordinator in the final (it rebuilds the final start list). The mode is chosen
    only when par+0xC8 changes, so the whole final stays in coordinator mode on the host.
TIMER_MODE (1 word, every game):
  0x12C91A8 cset w8, ne -> mov w8, wzr   the phase clock always uses the countdown, as guests already do.
Guests never have the coordinator, so for them nothing changes. Offline the clock would also lose the coordinator
display during point select (the countdown is drawn instead) [I: cosmetic].
"""
import cave_lib as C

for a, t in [(0x12C9194, 'ldr x8, [x21, #0x3388]'), (0x12C91A4, 'cmp x8, #0'), (0x12C91AC, 'str w8, [sp, #0x14]'),
             (0x12C93E8, 'ldr w8, [sp, #0x14]'), (0x12C93F0, 'ldr w8, [sp, #0x14]'), (0x12C9408, 'orr x0, x9, x8'),
             (0x13A1B40, 'bl #0x12c9160'), (0x13A1B90, 'cbz w8, #0x13a1be8')]:
    got = C.dis1(a, C.text_word(a))
    assert got == t, 'context %x: %s, expected %s' % (a, got, t)

g = C.Gen('timer_mode_gen', 'timer_mode_live.py')
NEW = 0x2A1F03E8                                           # mov w8, wzr (orr w8, wzr, wzr)
assert C.dis1(0x12C91A8, NEW) == 'mov w8, wzr'
groups = {'TIMER_MODE': [
    g.text_patch(0x12C91A8, 'cset w8, ne', NEW, 'phase clock: never the coordinator display')]}
assert groups['TIMER_MODE'][0][1:] == ('E8079F1A', 'E8031F2A', True)
print('\n'.join(g.listing))
C.write_live('timer_mode_live.py', groups, ['TIMER_MODE'], """
TIMER_MODE (generated by timer_mode_gen.py; timer4_notes.md): the phase clock never takes the point-select
coordinator display, so the host shows the phase countdown in the final like the guests. Apply on EVERY game.
Live-checked only with diag/twin/timer_fix_live.py (see there).""")
d, r = C.cpp_rows('TIMER_MODE', groups['TIMER_MODE'])
print(d + '\n' + r)
